<?php

namespace App\Modules\OnlineAdmission\Support;

use Illuminate\Validation\Rule;

/**
 * The public admission form's admin-configured fields, as the Website
 * `admission_form` block stores them (PageRenderService::admissionFormFields()).
 * Turns that config into server-side validation: one rule set per custom
 * field, plus the Required switches on the optional standard fields, so the
 * server enforces what the browser shows. Always built from the saved page,
 * never from the request, so an applicant can't add or change fields.
 */
final class AdmissionFormSchema
{
    /** Standard fields the admin can show/hide; every other key is a custom field. */
    private const STANDARD = ['last_name', 'blood_group', 'student_phone', 'photo', 'guardian', 'permanent_address', 'notes'];

    /** Standard fields whose Required switch the form honours ('guardian' is a section toggle only). */
    private const REQUIRABLE = ['last_name', 'blood_group', 'student_phone', 'photo', 'permanent_address', 'notes'];

    /** Field types the form renders; anything else renders (and validates) as text. */
    private const TYPES = ['text', 'textarea', 'select', 'number', 'date', 'file', 'checkbox'];

    /** @var array<string, array{label: string, type: string, required: bool, options: list<string>}> */
    private array $custom = [];

    /** @var list<string> */
    private array $requiredStandard = [];

    /**
     * @param  array<array-key, mixed>  $fields  normalized field config; [] when the page has no admission form
     */
    public function __construct(array $fields = [])
    {
        foreach ($fields as $key => $cfg) {
            if (! is_string($key) || ! is_array($cfg) || empty($cfg['enabled'])) {
                continue;
            }
            if (in_array($key, self::STANDARD, true)) {
                if (in_array($key, self::REQUIRABLE, true) && ! empty($cfg['required'])) {
                    $this->requiredStandard[] = $key;
                }

                continue;
            }
            // Keys are generated by the editor (custom_1000, ...); anything else
            // would break the custom.{key} validation path.
            if (! preg_match('/^[A-Za-z0-9_]{1,64}$/', $key)) {
                continue;
            }
            $label = is_string($cfg['label'] ?? null) && trim($cfg['label']) !== ''
                ? trim($cfg['label'])
                : ucfirst(str_replace('_', ' ', $key));
            $type = in_array($cfg['type'] ?? null, self::TYPES, true) ? $cfg['type'] : 'text';

            $this->custom[$key] = [
                'label' => $label,
                'type' => $type,
                'required' => ! empty($cfg['required']),
                'options' => self::options($cfg['options'] ?? null),
            ];
        }
    }

    /** @return array<string, array{label: string, type: string, required: bool, options: list<string>}> */
    public function customFields(): array
    {
        return $this->custom;
    }

    /**
     * Standard fields the admin marked Required (and left visible).
     *
     * @return list<string>
     */
    public function requiredStandardFields(): array
    {
        return $this->requiredStandard;
    }

    /**
     * Validation rules for every visible custom field, keyed custom.{key}.
     *
     * @return array<string, list<mixed>>
     */
    public function rules(): array
    {
        $rules = [];
        foreach ($this->custom as $key => $field) {
            if ($field['type'] === 'checkbox') {
                // The form always posts a hidden "0", so Required means "must be ticked".
                $rules["custom.{$key}"] = $field['required'] ? ['accepted'] : ['nullable', 'boolean'];

                continue;
            }

            $rules["custom.{$key}"] = [$field['required'] ? 'required' : 'nullable', ...match ($field['type']) {
                'textarea' => ['string', 'max:2000'],
                'number' => ['numeric'],
                'date' => ['date'],
                'file' => ['image', 'mimes:jpg,jpeg,png', 'max:1024'],
                'select' => $field['options'] !== [] ? ['string', Rule::in($field['options'])] : ['string', 'max:255'],
                default => ['string', 'max:255'],
            }];
        }

        return $rules;
    }

    /**
     * Readable names for validation messages ("Emergency contact is required").
     *
     * @return array<string, string>
     */
    public function attributes(): array
    {
        $names = [];
        foreach ($this->custom as $key => $field) {
            $names["custom.{$key}"] = $field['label'];
        }

        return $names;
    }

    /**
     * A select's options, stored either as a list or as the editor's "A, B" string.
     *
     * @return list<string>
     */
    private static function options(mixed $raw): array
    {
        $items = is_array($raw) ? $raw : (is_string($raw) ? explode(',', $raw) : []);
        $out = [];
        foreach ($items as $item) {
            if (is_scalar($item) && trim((string) $item) !== '') {
                $out[] = trim((string) $item);
            }
        }

        return array_values(array_unique($out));
    }
}
